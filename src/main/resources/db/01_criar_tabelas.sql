-- H2 (modo PostgreSQL) e PostgreSQL. Executado automaticamente pelo DatabaseInitializer.
-- IF NOT EXISTS não atualiza uma tabela antiga: mantenha este banco separado de outros projetos.
CREATE TABLE IF NOT EXISTS usuarios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(100) NOT NULL,
 email VARCHAR(160) NOT NULL,
 senha_hash VARCHAR(100) NOT NULL,
 criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
 CONSTRAINT uk_usuarios_email UNIQUE (email)
);
CREATE TABLE IF NOT EXISTS tipos_cartao (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(60) NOT NULL,
 descricao VARCHAR(255) NOT NULL,
 disponivel BOOLEAN NOT NULL DEFAULT TRUE,
 CONSTRAINT uk_tipos_cartao_nome UNIQUE (nome)
);
CREATE TABLE IF NOT EXISTS solicitacoes_cartao (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT NOT NULL,
 tipo_cartao_id BIGINT NOT NULL,
 solicitada_em TIMESTAMP WITH TIME ZONE NOT NULL,
 status VARCHAR(20) NOT NULL,
 CONSTRAINT ck_solicitacao_status CHECK (status IN ('PENDENTE','CANCELADA','EMITIDA')),
 CONSTRAINT fk_solicitacao_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
 CONSTRAINT fk_solicitacao_tipo FOREIGN KEY (tipo_cartao_id) REFERENCES tipos_cartao(id)
);
CREATE TABLE IF NOT EXISTS cartoes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 solicitacao_id BIGINT NOT NULL,
 emitido_em TIMESTAMP WITH TIME ZONE NOT NULL,
 status VARCHAR(20) NOT NULL,
 CONSTRAINT uk_cartao_solicitacao UNIQUE (solicitacao_id),
 CONSTRAINT ck_cartao_status CHECK (status IN ('ATIVO','BLOQUEADO')),
 CONSTRAINT fk_cartao_solicitacao FOREIGN KEY (solicitacao_id) REFERENCES solicitacoes_cartao(id)
);
CREATE INDEX IF NOT EXISTS idx_solicitacoes_usuario ON solicitacoes_cartao(usuario_id);
CREATE INDEX IF NOT EXISTS idx_solicitacoes_tipo ON solicitacoes_cartao(tipo_cartao_id);
